CREATE TABLE IF NOT EXISTS "__EFMigrationsHistory" (
    "MigrationId" varchar(150) NOT NULL,
    "ProductVersion" varchar(32) NOT NULL,
    CONSTRAINT "PK___EFMigrationsHistory" PRIMARY KEY ("MigrationId")
);

CREATE TABLE IF NOT EXISTS "FatoresEmissao" (
    "TipoCombustivel" varchar(30) NOT NULL,
    "FatorEmissao" double precision NOT NULL,
    "ConsumoMarchaLenta" double precision NOT NULL,
    "ConsumoAdicionalAceleracao" double precision NOT NULL,
