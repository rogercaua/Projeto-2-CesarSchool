CREATE TABLE IF NOT EXISTS "Users" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Nome" varchar(100) NOT NULL,
    "Email" varchar(150) NOT NULL,
    "PasswordHash" text NOT NULL,
    "Role" varchar(30) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_Users" PRIMARY KEY ("Id")
);

CREATE TABLE IF NOT EXISTS "LocaisUso" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Nome" varchar(100) NOT NULL,
    "TipoLocal" varchar(30) NOT NULL,
    CONSTRAINT "PK_LocaisUso" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_LocaisUso_ParametrosCenarioSemTag_TipoLocal"
        FOREIGN KEY ("TipoLocal")
        REFERENCES "ParametrosCenarioSemTag" ("TipoLocal")
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS "Veiculos" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UsuarioId" integer NOT NULL,
    "TipoVeiculo" varchar(30) NOT NULL,
    "TipoCombustivel" varchar(30) NOT NULL,
    CONSTRAINT "PK_Veiculos" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Veiculos_FatoresEmissao_TipoCombustivel"
        FOREIGN KEY ("TipoCombustivel")
        REFERENCES "FatoresEmissao" ("TipoCombustivel")
        ON DELETE RESTRICT,
    CONSTRAINT "FK_Veiculos_Users_UsuarioId"
        FOREIGN KEY ("UsuarioId")
        REFERENCES "Users" ("Id")
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "PassagensTag" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "VeiculoId" integer NOT NULL,
    "LocalUsoId" integer NOT NULL,
    "DataHora" timestamp with time zone NOT NULL,
    "Co2EvitadoKg" double precision NOT NULL,
    CONSTRAINT "PK_PassagensTag" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_PassagensTag_LocaisUso_LocalUsoId"
        FOREIGN KEY ("LocalUsoId")
        REFERENCES "LocaisUso" ("Id")
        ON DELETE RESTRICT,
    CONSTRAINT "FK_PassagensTag_Veiculos_VeiculoId"
        FOREIGN KEY ("VeiculoId")
        REFERENCES "Veiculos" ("Id")
        ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Users_Email" ON "Users" ("Email");
CREATE INDEX IF NOT EXISTS "IX_LocaisUso_TipoLocal" ON "LocaisUso" ("TipoLocal");
CREATE INDEX IF NOT EXISTS "IX_Veiculos_TipoCombustivel" ON "Veiculos" ("TipoCombustivel");
CREATE INDEX IF NOT EXISTS "IX_Veiculos_UsuarioId" ON "Veiculos" ("UsuarioId");
CREATE INDEX IF NOT EXISTS "IX_PassagensTag_LocalUsoId" ON "PassagensTag" ("LocalUsoId");
CREATE INDEX IF NOT EXISTS "IX_PassagensTag_VeiculoId" ON "PassagensTag" ("VeiculoId");

